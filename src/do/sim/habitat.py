"""A simulated habitat: the storage dynamics D.O. met on the live host, made cheap.

Why simulate at all. `DO_CONCEPT.md` section I ranks the learning signal as the problem
most likely to kill this project, and recommends a simulated world with dense feedback
before anything more ambitious. H4 shows why: ten episodes on the live host took 72
seconds and could only ever test one calibration factor. A learner that has to discover
what an action is *worth* - not just what it does - needs thousands of episodes, and
the live host cannot provide them.

What is simulated is deliberately narrow: one drive (frugality), the footprint it
measures, and the actions that move it, with parameter ranges anchored to what D.O.
measured on this machine.

    stocks    experiment matrices, bytecode, stale snapshots, the sqlite freelist, the
              live ledger: bytes an action can remove
    flows     bookkeeping. Every cycle appends ledger events and memory rows whether or
              not anything is done. H4 measured ~23 KB per cycle; it ate more than half
              of what the actions freed, and it is why H4's goal was never met.
    promises  every action estimates before acting. rotate_ledger assumes 2.0x
              compression; H4's learned correction (k = 1.74) implies the live ledger
              compressed ~7.7x. Vacuum ignores defragmentation.

Two dynamics the planner's one-step score cannot see, pulling in opposite directions:

    regrowth  __pycache__ is regenerated by the next import. Clearing it is a real gain
              this cycle and none a few cycles later. The planner over-values it.
    a flow    `consolidate_bookkeeping` records unchanged observations as deltas. It
              frees nothing now and cuts ledger growth for the rest of the run. The
              planner rejects it by construction: "predicted gain is zero or negative".
              It is NOT in the live registry. It exists here to test whether a learner
              can find value that a one-step score cannot represent.

The reward is not designed for this experiment. It is the frugality drive's weighted
error, computed by the same `Drive` class and config the live organism uses.

All quantities are integer bytes, so a run is exactly reproducible from its seed.
"""
from __future__ import annotations

import math
import random
from dataclasses import dataclass
from types import MappingProxyType

from ..drives import Drive

HORIZON = 16                    # decision cycles per run
WAIT = "wait"
FLOW_ACTION = "consolidate_bookkeeping"
# Fixed order, so iteration and tie-breaking are reproducible.
ACTIONS = (WAIT, "clear_experiment_matrix", "clear_bytecode", "prune_snapshots",
           "vacuum_memory", "rotate_ledger", FLOW_ACTION)

# The live registry's prior (capabilities/actions.py). The habitat's rotate_ledger
# promises on the same wrong assumption, for the same reason: nothing can know in
# advance how well its own history compresses.
PRIOR_COMPRESSION_RATIO = 2.0

# What an agent may see. Everything else on the habitat - the true compression ratio,
# how much consolidation cuts growth, when bytecode regrows, what VACUUM really
# reclaims - is the world's business, and has to be learned from outcomes or not at all.
OBSERVABLE = frozenset({
    "cycle", "total", "quota", "used_ratio", "error", "experiments", "bytecode",
    "prunable", "memory", "freelist", "ledger_live", "keep_live", "segments",
    "consolidated", "grew_last", "grew_ledger_last", "options",
})
# The parameters that decide what actions are worth. Never observed; a test checks
# that the agents module never names them.
HIDDEN = frozenset({"c10", "rho_pct", "defrag_pct", "free_pct", "bytecode_regrow",
                    "grow_ledger", "grow_memory"})


@dataclass(frozen=True)
class World:
    """One habitat's parameters. Drawn from a seed; never shown to an agent."""
    seed: int
    experiments: int
    bytecode: int
    bytecode_regrow: int        # cycles until the next import regenerates __pycache__
    snapshots: int
    snapshot_bytes: int
    snapshot_keep: int
    memory: int                 # sqlite file bytes, freelist included
    freelist: int
    free_pct: int               # share of memory growth that is superseded rows
    defrag_pct: int             # what VACUUM reclaims beyond the freelist
    ledger: int
    keep_live: int
    c10: int                    # true compression ratio x 10
    grow_ledger: int            # bookkeeping bytes per cycle
    grow_memory: int
    rho_pct: int                # ledger growth after consolidation, as % of before
    quota: int

    @property
    def growth_fraction(self) -> float:
        """Bookkeeping per cycle as a share of quota: the variable the hypothesis is
        about, and the one the results are stratified by."""
        return (self.grow_ledger + self.grow_memory) / self.quota


def sample_world(seed: int) -> World:
    """Draw a habitat. Ranges bracket what the live host measured; none were tuned.

    H4's workspace held a 72 KB experiment matrix and 6 KB of bytecode, its learned
    rotate_ledger correction (k = 1.74 against a 2.0x prior) implies a ~7.7x compression
    ratio, and its bookkeeping grew ~23 KB per cycle. Growth is drawn log-uniformly so
    that slow and fast habitats are equally represented: the hypothesis is about the
    difference between them.
    """
    r = random.Random(seed)

    def log_uniform(lo: int, hi: int) -> int:
        return int(math.exp(r.uniform(math.log(lo), math.log(hi))))

    experiments = r.randint(40_000, 120_000)
    bytecode = r.randint(3_000, 10_000)
    snapshots, snapshot_bytes = r.randint(3, 10), r.randint(1_500, 4_000)
    memory, freelist = r.randint(120_000, 260_000), r.randint(0, 20_000)
    ledger = r.randint(100_000, 250_000)
    total = experiments + bytecode + snapshots * snapshot_bytes + memory + ledger
    return World(
        seed=seed, experiments=experiments, bytecode=bytecode,
        bytecode_regrow=r.randint(1, 3),
        snapshots=snapshots, snapshot_bytes=snapshot_bytes, snapshot_keep=3,
        memory=memory, freelist=freelist,
        free_pct=r.randint(10, 40), defrag_pct=r.randint(0, 100),
        ledger=ledger, keep_live=15_000, c10=r.randint(30, 80),
        grow_ledger=log_uniform(2_000, 30_000), grow_memory=log_uniform(500, 6_000),
        rho_pct=r.randint(20, 60),
        # Starts out of band but not saturated: used/quota in [0.80, 0.98], where the
        # band's upper edge is 0.70.
        quota=int(total / r.uniform(0.80, 0.98)),
    )


class Habitat:
    """One run in one world. `step()` is the only way anything changes."""

    def __init__(self, world: World, drive_spec: dict, *, flow_action: bool = True,
                 regrowth: bool = True, horizon: int = HORIZON):
        self.world = world
        self.spec = drive_spec
        self.flow_action = flow_action
        self.regrowth = regrowth
        self.horizon = horizon
        self.reset()

    # ---- state ----------------------------------------------------------------
    def reset(self):
        w = self.world
        self.cycle = 0
        self.experiments, self.bytecode, self.regrow_in = w.experiments, w.bytecode, 0
        self.snapshots = w.snapshots
        self.memory, self.freelist = w.memory, w.freelist
        self.ledger_live, self.segments = w.ledger, 0
        self.consolidated = self.consolidating = False
        self.grew_last = self.grew_ledger_last = 0
        # One cycle of measured history before the first decision: the organism wakes
        # knowing how fast it grew last cycle, as it would after any earlier boot.
        self._grow()
        return self.observe()

    def total(self) -> int:
        w = self.world
        return (self.experiments + self.bytecode + self.snapshots * w.snapshot_bytes
                + self.memory + self.ledger_live + self.segments)

    def drive(self) -> Drive:
        """The live organism's frugality drive, evaluated on simulated measurements."""
        value = max(0.0, min(1.0, 1.0 - self.total() / self.world.quota))
        s = self.spec
        return Drive("frugality", value, s["target"], s["deadband"], s["weight"],
                     basis=f"habitat total={self.total()} of quota {self.world.quota}")

    def options(self) -> dict[str, int]:
        """Applicable actions -> each one's own estimate of the bytes it will free."""
        w = self.world
        out = {WAIT: 0}
        if self.experiments > 0:
            out["clear_experiment_matrix"] = self.experiments
        if self.bytecode > 0:
            out["clear_bytecode"] = self.bytecode
        if self.snapshots > w.snapshot_keep:
            out["prune_snapshots"] = (self.snapshots - w.snapshot_keep) * w.snapshot_bytes
        if self.freelist > 0:
            out["vacuum_memory"] = self.freelist          # ignores defragmentation
        if self.ledger_live > 2 * w.keep_live:            # the live registry's own rule
            sealable = self.ledger_live - w.keep_live
            out["rotate_ledger"] = int(sealable * (1 - 1 / PRIOR_COMPRESSION_RATIO))
        if self.flow_action and not (self.consolidated or self.consolidating):
            out[FLOW_ACTION] = 0                          # frees nothing now
        return out

    def observe(self) -> MappingProxyType:
        w = self.world
        obs = {
            "cycle": self.cycle, "total": self.total(), "quota": w.quota,
            "used_ratio": self.total() / w.quota,
            "error": self.drive().weighted_error,
            "experiments": self.experiments, "bytecode": self.bytecode,
            "prunable": max(0, self.snapshots - w.snapshot_keep) * w.snapshot_bytes,
            "memory": self.memory, "freelist": self.freelist,
            "ledger_live": self.ledger_live, "keep_live": w.keep_live,
            "segments": self.segments, "consolidated": self.consolidated,
            "grew_last": self.grew_last, "grew_ledger_last": self.grew_ledger_last,
            "options": MappingProxyType(self.options()),
        }
        assert obs.keys() == OBSERVABLE, "observation leaks or drops a field"
        return MappingProxyType(obs)

    # ---- dynamics -------------------------------------------------------------
    def step(self, action: str):
        opts = self.options()
        if action not in opts:
            raise ValueError(f"{action!r} is not applicable now")
        before = self.total()
        freed = self._execute(action)
        # Accounting must balance exactly, every step. A habitat that leaks or mints
        # bytes is one a learner can exploit, and its results would describe the bug.
        assert before - self.total() == freed >= 0, "action accounting does not balance"
        grew = self._grow()
        self.cycle += 1
        d = self.drive()
        info = {"action": action, "promised": opts[action], "freed": freed,
                "grew": grew, "error": d.weighted_error}
        return self.observe(), -d.weighted_error, self.cycle >= self.horizon, info

    def _execute(self, action: str) -> int:
        w = self.world
        if action == "clear_experiment_matrix":
            freed, self.experiments = self.experiments, 0
        elif action == "clear_bytecode":
            freed, self.bytecode = self.bytecode, 0
            self.regrow_in = w.bytecode_regrow if self.regrowth else -1
        elif action == "prune_snapshots":
            freed = (self.snapshots - w.snapshot_keep) * w.snapshot_bytes
            self.snapshots = w.snapshot_keep
        elif action == "vacuum_memory":
            # VACUUM returns the freelist and, unpredictably, some fragmentation.
            live = self.memory - self.freelist
            freed = self.freelist + min(self.freelist * w.defrag_pct // 100, live // 10)
            self.memory -= freed
            self.freelist = 0
        elif action == "rotate_ledger":
            sealed = self.ledger_live - w.keep_live
            segment = sealed * 10 // w.c10
            freed = sealed - segment
            self.ledger_live, self.segments = w.keep_live, self.segments + segment
        elif action == FLOW_ACTION:
            # Takes effect from the NEXT cycle: this cycle's records are already being
            # written the old way. So its immediate consequence is exactly WAIT's, and
            # all of its value lies in the future - a learner that cannot propagate
            # value through time cannot tell it from doing nothing.
            freed, self.consolidating = 0, True
        else:
            freed = 0
        return freed

    def _grow(self) -> int:
        """One cycle of bookkeeping, plus anything regenerated. It happens whatever the
        organism chose: the clock does not stop for a decision."""
        w = self.world
        ledger = w.grow_ledger * w.rho_pct // 100 if self.consolidated else w.grow_ledger
        self.consolidated = self.consolidated or self.consolidating
        self.ledger_live += ledger
        self.memory += w.grow_memory
        self.freelist += w.grow_memory * w.free_pct // 100
        regrown = 0
        if self.bytecode == 0 and self.regrow_in > 0:
            self.regrow_in -= 1
            if self.regrow_in == 0:
                self.bytecode = regrown = w.bytecode
        self.grew_last, self.grew_ledger_last = ledger + w.grow_memory + regrown, ledger
        return self.grew_last
