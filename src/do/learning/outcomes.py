"""Conditional reliability: learning that an action fails under some conditions.

`learning/__init__.py` learns *magnitude* - how wrong an action's own estimate is, as
one multiplicative factor. That is genuinely a policy update (it feeds the planner's
score), but it is context-free: it cannot represent "this works when the ledger is
large and not otherwise".

This module adds the conditional half. Every execution is recorded against a set of
**context features derived mechanically from state**, and reliability is estimated per
(action, feature). Nothing here encodes which features matter for which action; the
features are generated the same way for every action, and the statistics decide.

The honesty constraint that shapes the design: features must be generated by a rule
that has no per-action knowledge in it. If I wrote

    if action == "rotate_ledger": features.append("ledger_size:" + bucket(...))

then the relationship would be mine, discovered afterward and encoded, and the claim
"D.O. learned that X fails under Y" would be false. So features describe the
*situation*, never the action.
"""
from __future__ import annotations

import json
import time

SCHEMA = """
CREATE TABLE IF NOT EXISTS action_outcomes (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    ts REAL, boot_id TEXT, episode TEXT,
    action TEXT NOT NULL,
    features TEXT NOT NULL,          -- json list of context tokens
    predicted INTEGER, actual INTEGER,
    success INTEGER,                 -- did it do materially what it predicted
    stage TEXT, drive TEXT
);
CREATE INDEX IF NOT EXISTS idx_out_action ON action_outcomes(action);

CREATE TABLE IF NOT EXISTS feature_stats (
    action TEXT NOT NULL,
    feature TEXT NOT NULL,
    attempts INTEGER DEFAULT 0,
    successes INTEGER DEFAULT 0,
    sum_yield REAL DEFAULT 0.0,      -- actual/predicted, capped
    PRIMARY KEY (action, feature)
);
"""

# A yield below this fraction of the prediction counts as a failed action: it was
# chosen because it promised something, and it did not deliver. This is the only
# threshold in the module and it is applied identically to every action.
SUCCESS_FRACTION = 0.5


def ensure_schema(store) -> None:
    store.db.executescript(SCHEMA)
    store.db.commit()


def _bucket(x: float, edges=(0.1, 0.35, 0.7)) -> str:
    for i, e in enumerate(edges):
        if x < e:
            return f"q{i}"
    return f"q{len(edges)}"


def context_features(view, objective, stage: str) -> list[str]:
    """Describe the SITUATION, never the action.

    Generated identically regardless of which action is being considered, so any
    relationship between a feature and an action's success is discovered from
    outcomes rather than asserted here.
    """
    feats: list[str] = [f"stage:{stage}"]
    if objective is not None:
        feats.append(f"drive:{objective.drive}")
        span = max(1.0, abs(objective.start_value - objective.target_value))
        deficit = abs(objective.current_value - objective.target_value) / span
        feats.append(f"deficit:{_bucket(min(1.0, deficit))}")
        diag = objective.diagnosis or {}
        feats.append(f"diagnosed:{'yes' if diag else 'no'}")
        if diag.get("largest"):
            # Which component dominates is a fact about the situation. That it happens
            # to correlate with one action's usefulness is exactly what gets learned.
            feats.append(f"largest:{diag['largest']}")
        if diag:
            feats.append(f"sufficient:{'yes' if diag.get('sufficient') else 'no'}")
    net = view.val("world.network.reachable")
    if net is not None:
        feats.append(f"network:{'up' if net else 'down'}")
    return feats


def record(store, action: str, features: list[str], predicted: int, actual: int,
           stage: str, drive: str, episode: str, ledger=None) -> dict:
    """Fold one execution into the conditional statistics."""
    ensure_schema(store)
    ratio = (actual / predicted) if predicted > 0 else (1.0 if actual > 0 else 0.0)
    success = 1 if ratio >= SUCCESS_FRACTION else 0

    store.db.execute(
        "INSERT INTO action_outcomes (ts,boot_id,episode,action,features,predicted,"
        "actual,success,stage,drive) VALUES (?,?,?,?,?,?,?,?,?,?)",
        (time.time(), store.boot_id, episode, action, json.dumps(features),
         int(predicted), int(actual), success, stage, drive))
    for f in features:
        store.db.execute(
            "INSERT INTO feature_stats (action,feature,attempts,successes,sum_yield)"
            " VALUES (?,?,1,?,?) ON CONFLICT(action,feature) DO UPDATE SET"
            " attempts=feature_stats.attempts+1,"
            " successes=feature_stats.successes+?,"
            " sum_yield=feature_stats.sum_yield+?",
            (action, f, success, min(3.0, ratio), success, min(3.0, ratio)))
    store.db.commit()

    if ledger is not None and not success:
        from ..ledger import EventType
        ledger.append(EventType.BELIEF_UPDATE, {
            "subject": f"capability.{action}.reliability",
            "outcome": "under-delivered",
            "predicted": predicted, "actual": actual,
            "ratio": round(ratio, 3), "context": features,
            "note": "recorded against the situation it happened in, so the condition "
                    "can be learned rather than assumed"})
    return {"action": action, "ratio": round(ratio, 3), "success": bool(success)}


def reliability(store, action: str, features: list[str], prior: float = 0.7,
                strength: float = 2.0) -> tuple[float, str]:
    """P(this action delivers | this situation), Laplace-smoothed toward a prior.

    Smoothing matters more than the estimator here. With one observation an
    unsmoothed rate is 0.0 or 1.0, and the planner would swing violently off a single
    fluke - which would look like learning and be noise.
    """
    ensure_schema(store)
    rows = store.db.execute(
        "SELECT feature, attempts, successes FROM feature_stats"
        " WHERE action=? AND feature IN (%s)" % ",".join("?" * len(features)),
        (action, *features)).fetchall() if features else []
    if not rows:
        return prior, "no history in this situation; prior applied"
    att = sum(r["attempts"] for r in rows)
    suc = sum(r["successes"] for r in rows)
    est = (suc + prior * strength) / (att + strength)
    worst = min(rows, key=lambda r: (r["successes"] / r["attempts"]) if r["attempts"] else 1.0)
    return round(est, 4), (f"{suc}/{att} deliveries across {len(rows)} matching "
                           f"feature(s); weakest '{worst['feature']}'")


def export_state(store) -> dict:
    """Everything experience has taught, as data.

    This is what makes the ablation exact: the learning arm receives precisely this
    and the control arm receives nothing, with the environment identical for both.
    """
    ensure_schema(store)
    from . import ensure_schema as _cal_schema
    _cal_schema(store)
    return {
        "calibration": [dict(r) for r in store.db.execute(
            "SELECT * FROM calibration").fetchall()],
        "feature_stats": [dict(r) for r in store.db.execute(
            "SELECT * FROM feature_stats").fetchall()],
    }


def import_state(store, blob: dict) -> dict:
    """Transplant prior experience into a fresh organism."""
    ensure_schema(store)
    from . import ensure_schema as _cal_schema
    _cal_schema(store)
    n = 0
    for r in blob.get("calibration", []):
        store.db.execute(
            "INSERT OR REPLACE INTO calibration (action,k,samples,last_predicted_raw,"
            "last_predicted,last_actual,sum_ape,updated_ts) VALUES (?,?,?,?,?,?,?,?)",
            (r["action"], r["k"], r["samples"], r["last_predicted_raw"],
             r["last_predicted"], r["last_actual"], r["sum_ape"], r["updated_ts"]))
        n += 1
    for r in blob.get("feature_stats", []):
        store.db.execute(
            "INSERT OR REPLACE INTO feature_stats VALUES (?,?,?,?,?)",
            (r["action"], r["feature"], r["attempts"], r["successes"], r["sum_yield"]))
        n += 1
    store.db.commit()
    return {"rows_imported": n}


def learned_relations(store, min_attempts: int = 2) -> list[dict]:
    """What experience has actually taught, in a form a human can check.

    Reported as (action, situation, delivery rate) so a claim like "D.O. learned that
    X under-delivers when Y" can be verified against the rows rather than asserted.
    """
    ensure_schema(store)
    out = []
    for r in store.db.execute(
            "SELECT action, feature, attempts, successes, sum_yield FROM feature_stats"
            " WHERE attempts >= ? ORDER BY (CAST(successes AS REAL)/attempts), action",
            (min_attempts,)).fetchall():
        rate = r["successes"] / r["attempts"]
        out.append({
            "action": r["action"], "situation": r["feature"],
            "attempts": r["attempts"], "delivered": r["successes"],
            "delivery_rate": round(rate, 3),
            "mean_yield": round(r["sum_yield"] / r["attempts"], 3),
            "reads_as": (f"{r['action']} delivers {rate:.0%} of the time when "
                         f"{r['feature']}"),
        })
    return out
